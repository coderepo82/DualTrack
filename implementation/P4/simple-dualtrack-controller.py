from p4utils.utils.topology import Topology
from p4utils.utils.sswitch_API import *
from crc import Crc
import socket, struct, pickle, os
crc32_polinomials = [0x04C11DB7, 0xEDB88320, 0x04C11DB7, 0x04C11DB7, 0x04C11DB7]


class DualController(object):

    def __init__(self, sw_name, set_hash):

        self.topo = Topology(db="topology.db")
        self.sw_name = sw_name
        self.set_hash = set_hash
        self.thrift_port = self.topo.get_thrift_port(sw_name)
        self.controller = SimpleSwitchAPI(self.thrift_port)

        self.custom_calcs = self.controller.get_custom_crc_calcs()
        print(self.custom_calcs)
        self.init()

    def init(self):
        if self.set_hash:
            self.set_crc_custom_hashes()
        self.create_hashes()

    def set_forwarding(self):
        self.controller.table_add("forwarding", "set_egress_port", ['1'], ['2'])
        self.controller.table_add("forwarding", "set_egress_port", ['2'], ['1'])

    def reset_registers(self):
        len_ = len(self.controller.register_read("HTF"))
        for i in range(len_):
            self.controller.register_write("HTF", i, 0)
            self.controller.register_write("HTU", i, 0)
            self.controller.register_write("HTC", i, 0)
            self.controller.register_write("HTV", i, 0)
            self.controller.register_write("HTD", i, 0)
        len2_ = len(self.controller.register_read("QTE1"))
        for i in range(len2_):
            self.controller.register_write("QTE1", i, 0)
            self.controller.register_write("QTR1", i, 0)
            self.controller.register_write("QTP1", i, 0)
        for i in range(len2_):
            self.controller.register_write("QTE2", i, 0)
            self.controller.register_write("QTR2", i, 0)
            self.controller.register_write("QTP2", i, 0)

    def set_crc_custom_hashes(self):
        i = 0
        for custom_crc32, width in sorted(self.custom_calcs.items()):
            self.controller.set_crc32_parameters(custom_crc32, crc32_polinomials[i], 0xffffffff, 0xffffffff, True, True)
            i+=1

    def create_hashes(self):
        self.hashes = []
        for i in range(5):
            self.hashes.append(Crc(32, crc32_polinomials[i], True, 0xffffffff, True, 0xffffffff))

